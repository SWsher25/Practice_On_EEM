class Solution:
    def rob(self, nums: List[int]) -> int:
        if not nums:
            return 0

        # dp[i] будет хранить максимальную сумму, которую можно украсть до дома i.
        # Мы используем три переменные для оптимизации памяти вместо полного массива DP.
        
        # prev2 соответствует dp[i-2] (макс. сумма до дома i-2)
        prev2 = 0
        # prev1 соответствует dp[i-1] (макс. сумма до дома i-1)
        prev1 = 0

        for num in nums:
            # current_max будет соответствовать dp[i]
            # Максимум из двух вариантов:
            # 1. Украсть текущий дом: num + prev2 (нельзя украсть предыдущий)
            # 2. Не воровать из текущего дома: prev1 (максимум, достигнутый до этого дома)
            current_max = max(num + prev2, prev1)
            
            # Обновляем значения для следующей итерации
            prev2 = prev1
            prev1 = current_max
        
        return prev1
