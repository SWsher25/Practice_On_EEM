class Solution:
    def lengthOfLIS(self, nums: List[int]) -> int:
        # Инициализация dp-массива. dp[i] будет хранить длину самого длинного
        # возрастающего подпоследовательности, заканчивающейся элементом nums[i].
        n = len(nums)
        if n == 0:
            return 0

        dp = [1] * n  # Каждая элемента сам по себе является LIS длиной 1

        # Проходим по всем элементам, начиная со второго (индекс 1)
        for i in range(n):
            for j in range(i):
                # Если nums[i] больше nums[j], значит мы можем "расширить" LIS,
                # заканчивающийся на nums[j], добавлением nums[i].
                if nums[i] > nums[j]:
                    # Обновляем dp[i]: берем максимум из текущего значения и (длина до j + 1)
                    dp[i] = max(dp[i], dp[j] + 1)

        # Ответ — это максимальное значение в массиве dp, так как LIS может заканчиваться любым элементом.
        return max(dp) if dp else 0
